import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const frontendDir = path.resolve(scriptDir, '..');
const sourcePath = path.resolve(frontendDir, '..', 'contracts', 'product_workflow_actions.json');
const outputPath = path.resolve(frontendDir, 'src', 'workflow', 'productWorkflowActions.generated.ts');

const raw = JSON.parse(await readFile(sourcePath, 'utf8'));
if (!Array.isArray(raw) || raw.length === 0) {
  throw new Error('product workflow action manifest must be a non-empty array');
}

const actions = raw.map((item) => {
  if (!item || typeof item !== 'object') throw new Error('workflow action entries must be objects');
  const action = String(item.action || '');
  if (!/^[a-z][a-z0-9_]*$/.test(action)) throw new Error(`invalid workflow action: ${action}`);
  if (!['api', 'navigate'].includes(item.kind)) throw new Error(`invalid kind for ${action}`);
  if (!String(item.default_label || '').trim()) throw new Error(`missing default_label for ${action}`);
  if (item.kind === 'api' && (!item.client_export || !item.method || !item.route)) {
    throw new Error(`incomplete API contract for ${action}`);
  }
  if (item.kind === 'navigate' && !item.target) throw new Error(`missing target for ${action}`);
  return item;
}).sort((left, right) => String(left.action).localeCompare(String(right.action)));

const unique = new Set(actions.map((item) => item.action));
if (unique.size !== actions.length) throw new Error('duplicate product workflow actions');

const generated = `/* This file is generated by scripts/generate-product-workflow-actions.mjs. */\n`
  + `export const PRODUCT_WORKFLOW_ACTIONS = ${JSON.stringify(actions, null, 2)} as const;\n\n`
  + `export type GeneratedProductWorkflowAction = typeof PRODUCT_WORKFLOW_ACTIONS[number]['action'];\n`;

if (process.argv.includes('--check')) {
  if (!existsSync(outputPath)) {
    console.error(`missing generated workflow action file: ${outputPath}`);
    process.exit(1);
  }
  const current = await readFile(outputPath, 'utf8');
  if (current !== generated) {
    console.error('generated workflow action file is stale; run npm run contracts:generate');
    process.exit(1);
  }
  console.log('Product workflow action generated file is fresh');
} else {
  await writeFile(outputPath, generated, 'utf8');
  console.log(`Generated ${path.relative(frontendDir, outputPath)}`);
}
